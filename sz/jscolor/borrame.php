La definición acordada clasifica un 'hogar marginal' como uno en el que los habitantes sufren una o más de las siguientes 'privaciones domésticas' :

1. Falta de acceso a fuentes de agua mejoradas,
2. La falta de acceso a instalaciones sanitarias mejoradas,
3. Falta de suficiente espacio habitable,
4. Falta de durabilidad de la vivienda y,
5. Falta de seguridad de tenencia. Por extensión, el término 'habitante de tugurios' se refiere a una persona que vive en un hogar que carece de cualquiera de los atributos anteriores. 

